import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Counts the test suite and writes the result into the source tree.
 *
 * The engineer page and the engine footer both state how many invariants
 * hold the model. Typing that number by hand is exactly the unverifiable
 * claim the rest of this project argues against, and it had already gone
 * stale once: a footer said 137 while the suite contained 208.
 *
 * Reading the files at request time is not an option either, because the
 * engine page is a client component and node:fs cannot cross that boundary.
 * So the count is generated here, committed, and refreshed by prebuild. It
 * is derived either way; this is the derivation that works on both sides of
 * the server boundary.
 */

const OUT = "lib/engines/invariant-count.generated.ts";

function walk(dir, found = []) {
  for (const entry of readdirSync(dir)) {
    if (entry === "node_modules" || entry === ".next" || entry.startsWith(".")) continue;
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) walk(path, found);
    else if (entry.endsWith(".test.ts")) found.push(path);
  }
  return found;
}

const files = ["lib", "components"]
  .flatMap((d) => {
    try {
      return walk(d);
    } catch {
      return [];
    }
  })
  .map((file) => {
    const src = readFileSync(file, "utf8");
    // `it(` at a statement position. Deliberately simple: a cleverer parser
    // here would be a second thing to have to trust.
    const count = (src.match(/(^|\s)it\(/g) ?? []).length;
    return { file: file.replace(/\\/g, "/"), count };
  })
  .filter((g) => g.count > 0)
  .sort((a, b) => b.count - a.count || a.file.localeCompare(b.file));

const total = files.reduce((n, g) => n + g.count, 0);

writeFileSync(
  OUT,
  `/**
 * GENERATED by scripts/count-invariants.mjs. Do not edit by hand.
 *
 * Regenerated on every build. If this file disagrees with \`npm test\`, the
 * build that produced it is stale, not the suite.
 */

export interface SuiteFile {
  file: string;
  count: number;
}

export const SUITE_FILES: SuiteFile[] = ${JSON.stringify(files, null, 2)};

export const INVARIANT_COUNT = ${total};

export const SUITE_FILE_COUNT = ${files.length};
`,
  "utf8",
);

console.log(`invariants: ${total} across ${files.length} files -> ${OUT}`);
